;
; Правила (см. Contributing.md):
;   - Функция возвращает ошибку через CF=1 и si -> строка сообщения.
;   - Сообщение об ошибке:  '[!] EN: <текст>'  (N — код из этого реестра)
;   - Сообщение об успехе:  '[+] <текст>'      (без номера)
;   - Фатал Bootix / bios-api/disk: '[#] <текст>', без кода.
;
; Использование:
;   %include 'shared/errors.asm'    ; только константы — безопасно где угодно
;
;   ; Вариант А: сразу взять готовое сообщение по коду
;   mov ax, ERR_FILE_NOT_FOUND
;   call error_msg                  ; ax -> si, CF=0 при успехе
;
;   ; Вариант Б: обратиться к конкретной строке напрямую
;   mov si, err_file_not_found
;
; ❗️ Номера E1..EN СКВОЗНЫЕ по всему проекту. НЕ переиспользовать!
;    Новые коды — только в конец, с увеличением ERR_COUNT.

%ifndef ERRORS_ASM
%define ERRORS_ASM

; 0 — успех (для единообразия с CF=0)
%define ERR_NONE                  0

; --- Файловая система (FAT12) ----------------------------------------------
%define ERR_FILE_NOT_FOUND        1   ; E1  - файл не найден в корневом каталоге
%define ERR_BAD_CLUSTER           2   ; E2  - встречен дефектный кластер (0xFF7)
%define ERR_GUARD_OVERLAP         3   ; E3  - назначение пересекает защищённый регион
%define ERR_BROKEN_CHAIN          4   ; E4  - цепочка FAT повреждена (петля/служебный)

; --- Загрузчик / ранняя инициализация --------------------------------------
%define ERR_LOWER_MEMORY          5   ; E5  - int 12h не вернул объём памяти
%define ERR_MEMORY_MAP            6   ; E6  - int 15h/E820 недоступен
%define ERR_DISK_INIT             7   ; E7  - int 13h/08h не вернул геометрию

; --- Питание ---------------------------------------------------------------
%define ERR_SHUTDOWN_FAILED       8   ; E8  - APM не поддерживается / отказ

; --- RTC (часы реального времени) ------------------------------------------
%define ERR_RTC_TIME              9   ; E9  - int 1Ah/02h не вернул время
%define ERR_RTC_DATE             10   ; E10 - int 1Ah/04h не вернул дату

; --- .RLX-загрузчик приложений ---------------------------------------------
%define ERR_RLX_BAD_NAME         11   ; E11 - некорректное имя файла (не FAT 8.3)
%define ERR_RLX_MAGIC            12   ; E12 - магическое число .RLX не совпало
%define ERR_RLX_MODE             13   ; E13 - режим .RLX не поддерживается
%define ERR_RLX_HEADER           14   ; E14 - заголовок .RLX повреждён/короткий

; --- Сеть ------------------------------------------------------------------
%define ERR_NIC_NOT_FOUND        15   ; E15 - RTL8139 не найден на шине PCI
%define ERR_NIC_RESET_TIMEOUT    16   ; E16 - сброс NIC не завершился за таймаут

; --- Память ----------------------------------------------------------------
%define ERR_OUT_OF_MEMORY        17   ; E17 - аллокатор исчерпан (нет фреймов)
%define ERR_MAP_OUT_OF_RANGE     18   ; E18 - адрес вне доступного диапазона

; --- Ядро / системные вызовы -----------------------------------------------
%define ERR_INVALID_PCINFO       19   ; E19 - PCINFO null или повреждён
%define ERR_INVALID_SYSCALL      20   ; E20 - неизвестный номер syscall
%define ERR_INVALID_ARGUMENT     21   ; E21 - аргумент не прошёл валидацию
%define ERR_PIT_FREQ_RANGE       22   ; E22 - частота PIT вне диапазона
%define ERR_UNSUPPORTED_VIDEO    23   ; E23 - неизвестный видеорежим
%define ERR_IO_PORT              24   ; E24 - операция ввода/вывода не удалась

; Верхняя граница реестра — используется `error_msg` для валидации входа
%define ERR_COUNT                24

%endif