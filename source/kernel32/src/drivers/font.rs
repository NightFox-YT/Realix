// ❗️ Только для режима 320x200x256 (VGA_VIDEO_BUFFER) - в текстовом режиме
//    отрисовку символов делает аппаратный шрифт VGA (см. vga::text_print_char).
// ❗️ Минимальный набор символов - только то, что реально нужно интерфейсу
//    Cliff (см. commands::cliff): буквы A/C/L (надпись "CALC"), цифры,
//    арифметика и несколько служебных символов. Расширять по мере надобности.

use crate::drivers::vga::{self, Color};

pub const GLYPH_WIDTH: usize = 5;
pub const GLYPH_HEIGHT: usize = 7;
// Расстояние между символами (ширина глифа + 1 пиксель пробела)
pub const CHAR_ADVANCE: usize = GLYPH_WIDTH + 1;

/// Растровое представление одного символа: 7 строк, младшие 5 бит каждого
/// байта - пиксели строки слева направо (бит 4 = самый левый пиксель)
fn glyph(c: char) -> Option<[u8; GLYPH_HEIGHT]> {
    Some(match c {
        '0' => [0b01110, 0b10001, 0b10011, 0b10101, 0b11001, 0b10001, 0b01110],
        '1' => [0b00100, 0b01100, 0b00100, 0b00100, 0b00100, 0b00100, 0b01110],
        '2' => [0b01110, 0b10001, 0b00001, 0b00010, 0b00100, 0b01000, 0b11111],
        '3' => [0b11111, 0b00010, 0b00100, 0b00010, 0b00001, 0b10001, 0b01110],
        '4' => [0b00010, 0b00110, 0b01010, 0b10010, 0b11111, 0b00010, 0b00010],
        '5' => [0b11111, 0b10000, 0b11110, 0b00001, 0b00001, 0b10001, 0b01110],
        '6' => [0b00110, 0b01000, 0b10000, 0b11110, 0b10001, 0b10001, 0b01110],
        '7' => [0b11111, 0b00001, 0b00010, 0b00100, 0b01000, 0b01000, 0b01000],
        '8' => [0b01110, 0b10001, 0b10001, 0b01110, 0b10001, 0b10001, 0b01110],
        '9' => [0b01110, 0b10001, 0b10001, 0b01111, 0b00001, 0b00010, 0b01100],

        'A' => [0b01110, 0b10001, 0b10001, 0b11111, 0b10001, 0b10001, 0b10001],
        'C' => [0b01110, 0b10001, 0b10000, 0b10000, 0b10000, 0b10001, 0b01110],
        'E' => [0b11111, 0b10000, 0b10000, 0b11110, 0b10000, 0b10000, 0b11111],
        'F' => [0b11111, 0b10000, 0b10000, 0b11110, 0b10000, 0b10000, 0b10000],
        'I' => [0b01110, 0b00100, 0b00100, 0b00100, 0b00100, 0b00100, 0b01110],
        'L' => [0b10000, 0b10000, 0b10000, 0b10000, 0b10000, 0b10000, 0b11111],
        'O' => [0b01110, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b01110],
        'R' => [0b11110, 0b10001, 0b10001, 0b11110, 0b10100, 0b10010, 0b10001],
        'X' => [0b10001, 0b01010, 0b00100, 0b00100, 0b00100, 0b01010, 0b10001],

        '+' => [0b00000, 0b00100, 0b00100, 0b11111, 0b00100, 0b00100, 0b00000],
        '-' => [0b00000, 0b00000, 0b00000, 0b11111, 0b00000, 0b00000, 0b00000],
        '*' => [0b00000, 0b10101, 0b01110, 0b11111, 0b01110, 0b10101, 0b00000],
        '/' => [0b00001, 0b00010, 0b00010, 0b00100, 0b01000, 0b01000, 0b10000],
        '=' => [0b00000, 0b00000, 0b11111, 0b00000, 0b11111, 0b00000, 0b00000],
        '.' => [0b00000, 0b00000, 0b00000, 0b00000, 0b00000, 0b01100, 0b01100],
        '_' => [0b00000, 0b00000, 0b00000, 0b00000, 0b00000, 0b00000, 0b11111],
        ' ' => [0; GLYPH_HEIGHT],

        _ => return None,
    })
}

/// Отрисовка одного символа (левый верхний угол глифа в x,y)
/// Параметры:
///  - x, y: координаты левого верхнего угла (0-319, 0-199)
///  - c: символ (см. glyph - неизвестные символы рисуются как пробел)
///  - color: цвет переднего плана
pub fn draw_char(x: usize, y: usize, c: char, color: Color) {
    let rows = match glyph(c) {
        Some(rows) => rows,
        None => return, // Неизвестный символ - ничего не рисуем (не пробел)
    };

    for (row, bits) in rows.iter().enumerate() {
        for col in 0..GLYPH_WIDTH {
            // Бит (GLYPH_WIDTH-1-col) - самый левый пиксель первый
            if bits & (1 << (GLYPH_WIDTH - 1 - col)) != 0 {
                vga::set_pixel(x + col, y + row, color);
            }
        }
    }
}

/// Отрисовка строки текста (моноширинный шрифт, слева направо)
/// Параметры:
///  - x, y: координаты левого верхнего угла первого символа
///  - text: строка (символы вне набора glyph() рисуются как пробел)
///  - color: цвет переднего плана
pub fn draw_text(x: usize, y: usize, text: &str, color: Color) {
    for (i, c) in text.chars().enumerate() {
        draw_char(x + i * CHAR_ADVANCE, y, c, color);
    }
}

/// Ширина в пикселях строки текста заданной длины (для центрирования и т.п.)
pub fn text_width(len: usize) -> usize {
    if len == 0 { 0 } else { len * CHAR_ADVANCE - 1 }
}
