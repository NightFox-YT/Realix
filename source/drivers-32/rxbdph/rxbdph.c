#define VBE_DISPI_IOPORT_INDEX 0x01CE
#define VBE_DISPI_IOPORT_DATA 0x01CF
#define VBE_DISPI_INDEX_ID 0
#define VBE_DISPI_INDEX_XRES 1
#define VBE_DISPI_INDEX_YRES 2
#define VBE_DISPI_INDEX_BPP 3
#define VBE_DISPI_INDEX_ENABLE 4
#define VBE_DISPI_DISABLED 0x00
#define VBE_DISPI_ENABLED 0x01
#define VBE_DISPI_LFB_ENABLED 0x40

static inline void bga_write(uint16_t index, uint16_t data)
{
    __asm__ volatile("outw %%ax, %%dx" : : "a"(index), "d"((uint16_t)VBE_DISPI_IOPORT_INDEX));
    __asm__ volatile("outw %%ax, %%dx" : : "a"(data), "d"((uint16_t)VBE_DISPI_IOPORT_DATA));
}

static inline uint32_t *fb_ptr (uint16_t x, uint16_t y)
{
   uint8_t bpp_bytes = (g_vga.bpp == 32) ? 4 : 3;
   return (uint32_t*)((uint8_t*)g_vga.fb + y * g_vga.pitch + x * bpp_bytes);
}

/* ====== Initialization ====== */

int rxbdph_init(void)
{
    return rxbdph_init_hardware(1024, 768);
}

int rxbdph_init_hardware(uint16_t width, uint16_t height)
{
    if (width == 0 || height == 0) return EINVAL;
    uint8_t vdev = 2;
    uint8_t vbus = 0;
    uint8_t vfunc = 0;
    uint32_t reg0 = pci_read_config(vbus, vdev, vfunc, 0);
    uint16_t vendor_id = reg0 & 0xFFFF;
    uint16_t device_id = (reg0 >> 16) & 0xFFFF;

    if (vendor_id != 0x1234 || device_id != 0x1111)
    {
        int found = 0;
        for (uint8_t d = 0; d < 32; d++)
        {
            uint32_t r = pci_read_config(0, d, 0, 0);
            if ((r & 0xFFFF) == 0x1234 && ((r >> 16) & 0xFFFF) == 0x1111)
            {
                vdev = d;
                found = 1;
                break;
            }
        }
        if (!found) return ENOENT;
    }

    uint32_t bar0 = pci_read_config(vbus, vdev, vfunc, 0x10);
    if (bar0 & 1) return -103;

    uint32_t raw_fb = bar0 & ~0xF;

    uint32_t cmd_status = pci_read_config(vbus, vdev, vfunc, 0x04);
    uint32_t updated_cmd = (cmd_status & 0xFFFF0000) | (cmd_status & 0xFFFF) | (1 << 1) | (1 << 2);

    uint32_t addr_reg = (1 << 31) | (vbus << 16) | (vdev << 11) | (vfunc << 8) | 0x04;
    outl(0xCF8, addr_reg);
    outl(0xCFC, updated_cmd);

    bga_write(VBE_DISPI_INDEX_ENABLE, VBE_DISPI_DISABLED);
    bga_write(VBE_DISPI_INDEX_XRES, width);
    bga_write(VBE_DISPI_INDEX_YRES, height);
    bga_write(VBE_DISPI_INDEX_BPP, 32);
    bga_write(VBE_DISPI_INDEX_ENABLE, VBE_DISPI_ENABLED | VBE_DISPI_LFB_ENABLED);

    g_vga.fb = (uint32_t*)(uintptr_t)raw_fb;
    g_vga.width = width;
    g_vga.height = height;
    g_vga.bpp = 32;
    g_vga.pitch = width * 4;
    g_vga.initialized = 1;

    return SUCCESS;
}

/* ==== Manupulation ==== */

void rxbdph_put_pixel(uint16_t x, uint16_t y, uint32_t color)
{
    if (!g_vga.initialized) return;
    if (x >= g_vga.width || y >= g_vga.height) return;

    uint32_t *pixel = fb_ptr(x, y);

    if (g_vga.bpp == 32)
    {
        *pixel = color;
    } else if (g_vga.bpp == 24)
    {
        /* 24-bit: BGR order in memory, pack carefully */
        uint8_t *p = (uint8_t *)pixel;
        p[0] = (color >> 0) & 0xFF; /* B */
        p[1] = (color >> 8) & 0xFF; /* G */
        p[2] = (color >> 16) & 0xFF; /* R */
    }
}

uint32_t rxbdph_get_pixel(uint16_t x, uint16_t y)
{
    if (!g_vga.initialized) return 0;
    if (x >= g_vga.width || y >= g_vga.height) return 0;

    uint32_t *pixel = fb_ptr(x, y);

    if (g_vga.bpp == 32)
    {
        return *pixel;
    }
    else
    {
        uint8_t *p = (uint8_t*)pixel;
        return RGB(p[2], p[1], p[0]);
    }
}

/* Clear */
void rxbdph_clear(uint32_t color)
{
    if (!g_vga.initialized) return;

    if (g_vga.bpp == 32)
    {
      for (uint16_t y = 0; y < g_vga.height; y++)
      {
        uint32_t *line = (uint32_t*)((uint8_t*)g_vga.fb + y * g_vga.pitch);
        for (uint16_t x = 0; x < g_vga.width; x++) line[x] = color;
      }
    }
    else if (g_vga.bpp == 24)
    {
      uint8_t r = (color >> 16) & 0xFF;
      uint8_t g = (color >> 8) & 0xFF;
      uint8_t b = (color >> 0) & 0xFF;

      for (uint16_t y = 0; y < g_vga.height; y++)
      {
        uint8_t *line = ((uint8_t*)g_vga.fb + y * g_vga.pitch);
        for (uint16_t x = 0; x < g_vga.width; x++) {
          size_t idx = x * 3;
          line[idx] = b;
          line[idx + 1] = g;
          line[idx + 2] = r;
        }
      }
    }
}

void rxbdph_clear_black(void)
{
    rxbdph_clear(VGA_BLACK);
}

/* ===== Rasterization: Line (Bresenham) ===== */

void rxbdph_draw_line(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1, uint32_t color)
{
    if (!g_vga.initialized) return;

    int dx = (int)x1 - (int)x0;
    int dy = (int)y1 - (int)y0;
    int sx = (dx > 0) ? 1 : -1;
    int sy = (dy > 0) ? 1 : -1;
    dx = (dx < 0) ? -dx : dx;
    dy = (dy < 0) ? -dy : dy;

    int err = dx - dy;

    while (1)
    {
        rxbdph_put_pixel (x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx) { err += dx; y0 += sy; }
    }
}

/* ===== Rasterizetion: Rectangle ===== */

void rxbdph_draw_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint32_t color)
{
  if ((!g_vga.initialized && w == 0) || h == 0) return;

  uint16_t x1 = x + w - 1;
  uint16_t y1 = y + h - 1;

  rxbdph_draw_line (x, y, x1, y, color);
  rxbdph_draw_line (x1, y, x1, y1, color);
  rxbdph_draw_line (x1, y1, x, y1, color);
  rxbdph_draw_line (x, y1, x, y, color);
}

void rxbdph_fill_rect (uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint32_t color)
{
  if (!g_vga.initialized || w == 0 || h == 0) return;

  for (uint16_t row = y; row < y + h && row < g_vga.height; row++)
    for (uint16_t col = x; col < x + w && col < g_vga.width; col++) rxbdph_put_pixel(col, row, color);
}

/* ===== Rasterization: Circle (Midpoint) ===== */

void rxbdph_draw_circle (uint16_t cx, uint16_t cy, uint16_t r, uint32_t color)
{
  if (!g_vga.initialized || r == 0) return;

  int x = 0;
  int y = r;
  int d = 3 - 2 * (int)r;

  while (y >= x)
  {
    rxbdph_put_pixel(cx + x, cy + y, color);
    rxbdph_put_pixel(cx - x, cy + y, color);
    rxbdph_put_pixel(cx + x, cy - y, color);
    rxbdph_put_pixel(cx - x, cy - y, color);
    rxbdph_put_pixel(cx + x, cy + y, color);
    rxbdph_put_pixel(cx - x, cy + y, color);
    rxbdph_put_pixel(cx + x, cy - y, color);
    rxbdph_put_pixel(cx - x, cy - y, color);
    x++;
    if (d > 0)
    {
      y--;
      d = d + 4 * (x - y) + 10;
    } else d = d + 4 * x + 6;
  }
}

void rxbdph_fill_circle (uint16_t cx, uint16_t cy, uint16_t r, uint32_t color)
{
  if (!g_vga.initialized || r == 0) return;

  for (int y = -r; y <= r; y++)
    for (int x = -r; x <= r; x++)
      if (x * x + y * y <= r * r) rxbdph_put_pixel(cx + x, cy + y, color);
}

/* ===== Text Rendering ===== */
void rxbdph_draw_char (uint16_t x, uint16_t y, char c, uint32_t fg, uint32_t bg, int transparent)
{
  if (!g_vga.initialized) return;
  if (c < 32 || c > 127) c = '?';

  const uint8_t *glyph = font_bitmap[(uint8_t)c - 32];

  for (int row = 0; row < FONT_HEIGHT; row++)
  {
    uint8_t row_bits = glyph[row];
    for (int col = 0; col < FONT_WIDTH; col++)
    {
      if (row_bits & (0x80 >> col)) rxbdph_put_pixel (x + col, y + row, fg);
      else if (!transparent) rxbdph_put_pixel (x + col, y + row, bg);
    }
  }
}

void rxbdph_draw_string (uint16_t x, uint16_t y, const char *str, uint32_t fg, uint32_t bg, int transparent)
{
  if (!str) return;

  uint16_t cx = x;
  while (*str)
  {
    if (*str == '\n')
    {
      y += FONT_HEIGHT;
      cx = x;
      str++;
      continue;
    }
    rxbdph_draw_char (cx, y, *str, fg, bg, transparent);
    cx += FONT_WIDTH;
    str++;
  }
}

void rxbdph_draw_stringn(uint16_t         x,
                         uint16_t         y,
                         const char *str,
                         size_t      n,
                         uint32_t         fg,
                         uint32_t         bg,
                         int         transparent)
{
  if (!str) return;

  uint16_t cx = x;
  for (size_t i = 0; i < n && str[i]; i++)
  {
    if (str[i] == '\n')
    {
      y += FONT_HEIGHT;
      cx = x;
      continue;
    }
    rxbdph_draw_char(cx, y, str[i], fg, bg, transparent);
    cx += FONT_WIDTH;
  }
}
